"""Builds src/features/map/regions.ts: the 14 economic regions of Azerbaijan as SVG paths.

Input: geoBoundaries AZE ADM2 (districts), CC BY-SA 3.0, https://www.geoboundaries.org
  python3 scripts/build-regions.py path/to/geoBoundaries-AZE-ADM2_simplified.geojson
Needs shapely. Districts are merged into regions and projected with the same scales as
src/features/map/geo.ts (the map box is 400 x 325.9).
"""
import json, sys
from shapely.geometry import shape
from shapely.ops import unary_union

# name: (English, Russian, Azerbaijani, districts as spelled by geoBoundaries)
REGIONS = {
    "baku": ("Baku", "Бакинский", "Bakı", ["Baku City"]),
    "nakhchivan": ("Nakhchivan", "Нахчыванский", "Naxçıvan", ["Nakhchivan City", "Babek District", "Julfa District", "Kangarli District", "Ordubad District", "Sadarak District", "Shahbuz District", "Sharur District"]),
    "absheron-khizi": ("Absheron-Khizi", "Абшерон-Хызинский", "Abşeron-Xızı", ["Sumqayit City", "Absheron District", "Khizi District"]),
    "mountainous-shirvan": ("Mountainous Shirvan", "Горно-Ширванский", "Dağlıq Şirvan", ["Agsu District", "Ismailli District", "Gobustan District", "Shamakhi District"]),
    "ganja-dashkasan": ("Ganja-Dashkasan", "Гянджа-Дашкесанский", "Gəncə-Daşkəsən", ["Ganja City", "Naftalan City", "Dashkasan District", "Goranboy District", "Goygol District", "Samukh District"]),
    "gazakh-tovuz": ("Gazakh-Tovuz", "Газах-Товузский", "Qazax-Tovuz", ["Agstafa District", "Gadabay District", "Qazakh District", "Shamkir District", "Tovuz District"]),
    "karabakh": ("Karabakh", "Карабахский", "Qarabağ", ["Khankendi City", "Aghjabadi District", "Agdam District", "Barda District", "Fuzuli District", "Khojaly District", "Khojavend District", "Shusha City", "Shusha District", "Tartar District"]),
    "eastern-zangezur": ("Eastern Zangezur", "Восточно-Зангезурский", "Şərqi Zəngəzur", ["Jabrayil District", "Kalbajar District", "Qubadli District", "Lachin District", "Zangilan District"]),
    "guba-khachmaz": ("Guba-Khachmaz", "Губа-Хачмазский", "Quba-Xaçmaz", ["Khachmaz District", "Quba District", "Qusar District", "Siazan District", "Shabran District"]),
    "lankaran-astara": ("Lankaran-Astara", "Ленкорань-Астаринский", "Lənkəran-Astara", ["Astara District", "Jalilabad District", "Lerik District", "Lankaran District", "Lankaran City", "Masally District", "Yardymli District"]),
    "central-aran": ("Central Aran", "Центральный Аран", "Mərkəzi Aran", ["Mingachevir City", "Agdash District", "Goychay District", "Kurdamir District", "Ujar District", "Yevlakh City", "Yevlakh District", "Zardab District"]),
    "mil-mugan": ("Mil-Mugan", "Миль-Муганский", "Mil-Muğan", ["Beylagan District", "Imishli District", "Saatly District", "Sabirabad District"]),
    "shirvan-salyan": ("Shirvan-Salyan", "Ширван-Сальянский", "Şirvan-Salyan", ["Shirvan City", "Bilasuvar District", "Hajigabul District", "Neftchala District", "Salyan District"]),
    "sheki-zagatala": ("Sheki-Zagatala", "Шеки-Загатальский", "Şəki-Zaqatala", ["Balakan District", "Qakh District", "Qabala District", "Oghuz District", "Shaki City", "Shaki District", "Zaqatala District"]),
}

def project(lng, lat):
    return (362.7 + (lng - 49.8671) * 71.24, 138.0 - (lat - 40.4093) * 93.2)

def ring(coords):
    pts = [project(*c) for c in coords]
    return "M" + " L".join("%.1f %.1f" % p for p in pts) + "Z"

def path(geom):
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    return " ".join(ring(r.exterior.coords) + "".join(" " + ring(i.coords) for i in r.interiors) for r in polys)

data = json.load(open(sys.argv[1]))
districts = {}
for f in data["features"]:
    districts.setdefault(f["properties"]["shapeName"], []).append(shape(f["geometry"]))
used = {d for r in REGIONS.values() for d in r[3]}
missing = sorted(set(districts) - used)
if missing:
    sys.exit("districts not in any region: %s" % missing)
unknown = sorted(used - set(districts))
if unknown:
    sys.exit("districts not in the data: %s" % unknown)

shapes = {}
rows = []
for key, (en, ru, az, names) in REGIONS.items():
    parts = [g for n in names for g in districts[n]]
    merged = unary_union([p.buffer(0.002) for p in parts]).buffer(-0.002).simplify(0.002)
    biggest = max(merged.geoms, key=lambda g: g.area) if merged.geom_type == "MultiPolygon" else merged
    c = biggest.representative_point()
    x, y = project(c.x, c.y)
    shapes[key] = merged
    rows.append([key, en, ru, az, path(merged), x, y, 0])

# Neighbouring regions get different tones (greedy colouring), so borders read at a glance.
tones = {}
for row in rows:
    key = row[0]
    taken = {tones[o] for o in tones if shapes[key].buffer(0.01).intersects(shapes[o])}
    tones[key] = next(t for t in range(8) if t not in taken)
    row[7] = tones[key]

out = ["// Generated by scripts/build-regions.py. Do not edit by hand.",
       "// Boundaries: geoBoundaries (https://www.geoboundaries.org), CC BY-SA 3.0, projected to the",
       "// 400 x 325.9 map box shared with journeys/route-geo.ts.",
       "export type Region = {", "  id: string;", "  name: [string, string, string];", "  path: string;", "  label: { x: number; y: number };",
       "  tone: number;", "};",
       "export const regions: Region[] = ["]
for key, en, ru, az, d, x, y, tone in rows:
    out.append("  {\n    id: %s,\n    name: [%s, %s, %s],\n    path: %s,\n    label: { x: %.1f, y: %.1f },\n    tone: %d,\n  }," % tuple(json.dumps(v, ensure_ascii=False) if isinstance(v, str) else v for v in (key, en, ru, az, d, x, y, tone)))
out.append("];")
open("src/features/map/regions.ts", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("regions", len(rows))
